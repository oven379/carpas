/** Иллюстрация в статье. phone — вертикальный скрин телефона (ограничиваем высоту). */
function Fig({ src, alt, caption, phone = false }) {
  return (
    <figure className={`blogFig${phone ? ' blogFig--phone' : ''}`}>
      <img src={src} alt={alt} loading="lazy" />
      {caption ? <figcaption>{caption}</figcaption> : null}
    </figure>
  )
}

/** Встроенное видео RuTube (16:9) + ссылка «Смотреть на RuTube». id — хэш из URL видео. */
function VideoEmbed({ id, href, title }) {
  return (
    <figure className="blogVideo">
      <div className="blogVideo__frame">
        <iframe
          src={`https://rutube.ru/play/embed/${id}`}
          title={title}
          frameBorder="0"
          allow="clipboard-write; autoplay"
          allowFullScreen
          loading="lazy"
        />
      </div>
      <figcaption>
        <a href={href} target="_blank" rel="noopener noreferrer">
          Смотреть на RuTube →
        </a>
      </figcaption>
    </figure>
  )
}

